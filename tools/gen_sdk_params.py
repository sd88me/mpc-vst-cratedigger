#!/usr/bin/env python3
"""vst/params.json -> src/sdk/params_gen.h: the parameter table of the SDK front end (src/sdk/CrateDiggerPlugin.cpp).
Order = vst/params.json = vst/params.lock (checked): the VST parameter index that saved projects and Q-Link maps bind to. Append only."""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
spec = json.load(open(os.path.join(ROOT, "vst/params.json")))
lock = [l.strip() for l in open(os.path.join(ROOT, "vst/params.lock")) if l.strip()]
keys = [p["key"] for p in spec["params"]]
if keys[:len(lock)] != lock:
    raise SystemExit("params.json no longer starts with params.lock: the order is frozen (append only)")
types = {"stepper": "T_STEPPER", "trigger": "T_TRIGGER", "float": "T_FLOAT", "readout": "T_READOUT", "slot": "T_SLOT", "option": "T_OPTION"}
L = ["/* generated by tools/gen_sdk_params.py from vst/params.json - do not edit */", "#pragma once",
     "enum { T_STEPPER, T_TRIGGER, T_FLOAT, T_READOUT, T_SLOT, T_OPTION };",
     "typedef struct { const char *key, *name; int type; float min, max, def; } param_t;", "enum {"]
L += ["    P_%s," % k.upper() for k in keys]
L += ["    NPARAMS", "};", "static const param_t PARAMS[NPARAMS] = {"]
for p in spec["params"]:
    lo, hi = p.get("min", 0), p.get("max", 1)
    d = p.get("default", lo)
    L.append('    {"%s", "%s", %s, %rf, %rf, %rf},' % (p["key"], p["name"], types[p["type"]], float(lo), float(hi), float(d)))
L += ["};", ""]
open(os.path.join(ROOT, "src/sdk/params_gen.h"), "w").write("\n".join(L))
print("src/sdk/params_gen.h: %d params" % len(keys))
